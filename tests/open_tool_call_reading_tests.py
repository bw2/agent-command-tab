import json
import os
import tempfile
import unittest

from agent_command_tab.open_tool_call_reading import (read_open_tool_call_from_claude_code_transcript,
                                                      read_open_tool_call_from_codex_conversation_file)

NO_OPEN_TOOL_CALL = {"open_tool_name": "", "open_tool_started_at": None}


def write_jsonl_file(folder, records):
    path = os.path.join(folder, "conversation.jsonl")
    with open(path, "w") as file:
        for record in records:
            file.write(json.dumps(record) + "\n")
    return path


def claude_user_record(content, **extra_fields):
    return dict({"type": "user", "message": {"role": "user", "content": content}}, **extra_fields)


def claude_assistant_record(*blocks, **extra_fields):
    return dict({"type": "assistant", "message": {"role": "assistant", "content": list(blocks)}}, **extra_fields)


def claude_bash_call(tool_use_id="t1"):
    return claude_assistant_record({"type": "tool_use", "id": tool_use_id, "name": "Bash", "input": {"command": "pytest"}})


def codex_event(payload):
    return {"type": "event_msg", "payload": payload}


def codex_response_item(payload):
    return {"type": "response_item", "payload": payload}


class ReadClaudeCodeOpenToolCallTests(unittest.TestCase):
    def read(self, records):
        with tempfile.TemporaryDirectory() as folder:
            return read_open_tool_call_from_claude_code_transcript(write_jsonl_file(folder, records))

    def test_an_open_tool_call_and_when_its_record_was_written(self):
        self.assertEqual(self.read([
            claude_user_record("Fix the failing test"),
            claude_assistant_record({"type": "text", "text": "Looking at the test now."}),
            dict(claude_bash_call(), timestamp="2026-10-28T11:12:04.500Z"),
        ]), {"open_tool_name": "Bash", "open_tool_started_at": 1793185924.5})

    def test_an_answered_tool_call_or_one_followed_by_text_is_not_open(self):
        self.assertEqual(self.read([
            claude_user_record("Fix it"),
            claude_bash_call("t1"),
            claude_user_record([{"type": "tool_result", "tool_use_id": "t1", "content": "ok"}]),
            claude_assistant_record({"type": "tool_use", "id": "t2", "name": "Read", "input": {"file_path": "/a"}}),
            claude_assistant_record({"type": "text", "text": "All tests pass."}),
        ]), NO_OPEN_TOOL_CALL)

    def test_an_answered_tool_call_is_not_open_with_nothing_said_after_it(self):
        # No text after the answer, so only its tool_result keeps the call from counting as open.
        self.assertEqual(self.read([
            claude_user_record("Fix it"),
            claude_bash_call("t1"),
            claude_user_record([{"type": "tool_result", "tool_use_id": "t1", "content": "ok"}]),
        ]), NO_OPEN_TOOL_CALL)

    def test_a_call_from_an_earlier_turn_is_not_open_after_a_new_prompt(self):
        self.assertEqual(self.read([claude_user_record("First request"), claude_bash_call(), claude_user_record("Second request")]),
                         NO_OPEN_TOOL_CALL)

    def test_records_claude_code_writes_itself_and_subagent_records_start_no_turn(self):
        self.assertEqual(self.read([
            claude_user_record("The real prompt"),
            claude_bash_call(),
            claude_user_record("<local-command-stdout>Session: 12% used</local-command-stdout>"),
            claude_user_record("Caveat: the messages below were generated by the user"),
            claude_user_record("Some instructions", isMeta=True),
            claude_user_record("This session is being continued from a previous conversation", isCompactSummary=True),
            claude_user_record("A subagent's prompt", isSidechain=True),
            claude_assistant_record({"type": "text", "text": "A subagent's answer."}, isSidechain=True),
        ])["open_tool_name"], "Bash")

    def test_a_prompt_that_starts_with_a_tag_is_the_users(self):
        self.assertEqual(self.read([claude_user_record("An earlier prompt"), claude_bash_call(),
                                    claude_user_record('<pasted_content id="1">the log</pasted_content> why does this fail?')]),
                         NO_OPEN_TOOL_CALL)

    def test_a_slash_command_or_skill_and_a_task_notification_start_a_turn(self):
        self.assertEqual(self.read([
            claude_user_record("commit and push"),
            claude_bash_call(),
            claude_user_record("<command-message>code-review-local</command-message>\n<command-name>/code-review-local</command-name>\n"
                               "<command-args>run_all_steps.py</command-args>"),
            claude_assistant_record({"type": "thinking", "thinking": "..."}),
        ]), NO_OPEN_TOOL_CALL)
        self.assertEqual(self.read([
            claude_user_record("run the tests in the background"),
            claude_bash_call(),
            {"type": "last-prompt", "lastPrompt": "run the tests in the background"},
            claude_user_record("<task-notification>\n<task-id>b1</task-id>\n<status>completed</status>\n</task-notification>"),
            claude_assistant_record({"type": "thinking", "thinking": "..."}),
        ]), NO_OPEN_TOOL_CALL)

    def test_a_message_from_another_claude_code_session_starts_a_turn(self):  # code review, 2026-10-28
        # As Claude Code wrote one on this Mac (SendMessage from another session).
        peer_message = claude_user_record("Another Claude session sent a message:\n<cross-session-message from-name=\"a7\">I renamed "
                                          "the column.</cross-session-message>", isMeta=True, turnOrigin="peer", promptSource="system",
                                          origin={"kind": "peer", "name": "a7"})
        # So does a notice that a session it asked about went idle.
        idle_notice = claude_user_record('[Cross-session idle notice] "a7", which you asked to be notified about, is idle.', isMeta=True,
                                         turnOrigin="system", promptSource="system")
        for turn_starting_record in (peer_message, idle_notice):
            self.assertEqual(self.read([claude_user_record("fix the bug"), claude_bash_call(), turn_starting_record,
                                        claude_assistant_record({"type": "thinking", "thinking": "..."})]), NO_OPEN_TOOL_CALL)


class ReadCodexOpenToolCallTests(unittest.TestCase):
    def read(self, records):
        with tempfile.TemporaryDirectory() as folder:
            return read_open_tool_call_from_codex_conversation_file(write_jsonl_file(folder, records))

    def test_codex_0_163_items_and_an_open_command(self):
        # Text said before the call doesn't hide it: the call is the newest record.
        self.assertEqual(self.read([
            codex_response_item({"type": "message", "role": "user", "content": [{"type": "input_text", "text": "# AGENTS.md"}]}),
            codex_event({"type": "item_completed", "item": {"type": "UserMessage", "content": [{"type": "text", "text": "Run the tests"}]}}),
            codex_event({"type": "item_completed", "item": {"type": "AgentMessage", "content": [{"type": "Text", "text": "Running them."}]}}),
            dict(codex_response_item({"type": "custom_tool_call", "name": "exec", "call_id": "c1",
                                      "input": 'text(await tools.exec_command({cmd:"python3 -m unittest",yield_time_ms:1000}))'}),
                 timestamp="2026-10-28T11:10:52.000Z"),
        ]), {"open_tool_name": "exec", "open_tool_started_at": 1793185852.0})

    def test_an_open_polling_call_without_a_command_counts_and_answered_calls_dont(self):
        # The open wait counts as a tool the agent waits on (user request, 2026-10-28).
        self.assertEqual(self.read([
            codex_event({"type": "user_message", "message": "Sleep for a while"}),
            codex_response_item({"type": "custom_tool_call", "name": "exec", "call_id": "c1", "input": '{cmd:"sleep 45"}'}),
            codex_response_item({"type": "custom_tool_call_output", "call_id": "c1", "output": "still running"}),
            codex_response_item({"type": "function_call", "name": "wait", "call_id": "c2", "arguments": '{"cell_id":"3"}'}),
        ]), {"open_tool_name": "wait", "open_tool_started_at": None})  # no timestamp in this record

    def test_earlier_codex_versions_events_and_a_call_followed_by_a_message(self):
        self.assertEqual(self.read([
            codex_event({"type": "user_message", "message": "Explain the error"}),
            codex_response_item({"type": "function_call", "name": "shell", "call_id": "c1",
                                 "arguments": json.dumps({"command": ["ls", "-la"]})}),
            codex_response_item({"type": "function_call_output", "call_id": "c1", "output": "..."}),
        ]), NO_OPEN_TOOL_CALL)
        self.assertEqual(self.read([
            codex_event({"type": "user_message", "message": "Explain the error"}),
            codex_response_item({"type": "function_call", "name": "shell", "call_id": "c1", "arguments": "{}"}),
            codex_event({"type": "agent_message", "message": "The error comes from a missing file."}),
        ]), NO_OPEN_TOOL_CALL)


if __name__ == "__main__":
    unittest.main()
